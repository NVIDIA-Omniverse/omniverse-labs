DEFAULT_ELEVATION_DEGREES = 90.0
DEFAULT_TURBIDITY = 2.9
DEFAULT_ALBEDO = 0.3


def _bracket(values: tuple, x: float) -> tuple[int, int, float]:
    x = min(max(x, values[0]), values[-1])
    for i in range(len(values) - 1):
        if x <= values[i + 1]:
            span = values[i + 1] - values[i]
            return i, i + 1, (x - values[i]) / span if span else 0.0
    return len(values) - 1, len(values) - 1, 0.0


def hosek_wilkie_mean_radiance(
    elevation_degrees: float = DEFAULT_ELEVATION_DEGREES,
    turbidity: float = DEFAULT_TURBIDITY,
    albedo: float = DEFAULT_ALBEDO,
) -> tuple[float, float, float]:
    ei = _bracket(ELEVATIONS, elevation_degrees)
    ti = _bracket(TURBIDITIES, turbidity)
    ai = _bracket(ALBEDOS, albedo)
    nt, na = len(TURBIDITIES), len(ALBEDOS)
    out = [0.0, 0.0, 0.0]
    for e, we in ((ei[0], 1.0 - ei[2]), (ei[1], ei[2])):
        for t, wt in ((ti[0], 1.0 - ti[2]), (ti[1], ti[2])):
            for a, wa in ((ai[0], 1.0 - ai[2]), (ai[1], ai[2])):
                weight = we * wt * wa
                if weight:
                    row = _TABLE[(e * nt + t) * na + a]
                    for c in range(3):
                        out[c] += weight * row[c]
    return (out[0], out[1], out[2])


def _direction_elevation_degrees(direction: Any) -> float:
    try:
        x, y, z = (float(direction[0]), float(direction[1]), float(direction[2]))
    except (TypeError, ValueError, IndexError, KeyError):
        return DEFAULT_ELEVATION_DEGREES
    length = math.sqrt(x * x + y * y + z * z)
    if length < 1.0e-9:
        return DEFAULT_ELEVATION_DEGREES
    return math.degrees(math.asin(min(1.0, max(-1.0, z / length))))


def sky_texture_radiance(node: Any) -> tuple[tuple[float, float, float], str | None]:
    """Return (linear RGB, note) for a Sky Texture node; the note is set when the value is approximate."""

    sky_type = str(getattr(node, "sky_type", "HOSEK_WILKIE") or "HOSEK_WILKIE")
    if sky_type != "HOSEK_WILKIE":
        return hosek_wilkie_mean_radiance(), "sky_texture_non_hosek_wilkie_default_used:" + sky_type
    elevation = _direction_elevation_degrees(getattr(node, "sun_direction", (0.0, 0.0, 1.0)))
    turbidity = float(getattr(node, "turbidity", DEFAULT_TURBIDITY))
    albedo = float(getattr(node, "ground_albedo", DEFAULT_ALBEDO))
    return hosek_wilkie_mean_radiance(max(0.0, elevation), turbidity, albedo), "sky_texture_horizon_band_mean"
