#!/usr/bin/env python3
"""Render Blender Markdown guides into the static Pages site (requires pandoc).

Run from any directory: python scripts/sync-blender-guides.py
Canonical prose lives under projects/ov-blender-example/docs/. The landing page
owns the shared page shell; this command leaves its article content unchanged.
"""
from pathlib import Path
import re
import shutil
import html
from urllib.parse import urlsplit
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'projects/ov-blender-example/docs'
DEST = ROOT / 'docs/projects/ov-blender-example'
GUIDES = ('install-guide', 'render-guide', 'physics-guide', 'developer-guide',
          'support-platforms', 'release-notes-0.2')


def main():
    # Copy this guide set's media; other project images are not site dependencies.
    media = tuple((SOURCE / 'images').glob('marble-*'))
    if media:
        (DEST / 'images').mkdir(exist_ok=True)
        for asset in media:
            shutil.copy2(asset, DEST / 'images' / asset.name)
    shell = (DEST / 'index.html').read_text()
    start = shell.index('    <article ')
    end = shell.index('    </article>', start) + len('    </article>')
    for slug in GUIDES:
        source = SOURCE / (slug + '.md')
        markdown = source.read_text()
        title = next(line[2:] for line in markdown.splitlines() if line.startswith('# '))
        body = subprocess.run(['pandoc', '--from=gfm', '--to=html5', '--wrap=none'],
                              input=markdown, text=True, check=True,
                              capture_output=True).stdout
        for guide in GUIDES:
            body = body.replace('href="' + guide + '.md', 'href="' + guide + '.html')
        # Resolve project-relative source references to their public repository path.
        # Newly generated guide links and in-page anchors remain local to Pages.
        def source_link(match):
            target = match[1]
            parts = urlsplit(target)
            if parts.scheme or target.startswith(('#', 'images/')) or parts.path in {g + '.html' for g in GUIDES}:
                return match[0]
            resolved = (source.parent / parts.path).resolve().relative_to(ROOT).as_posix()
            anchor = '#' + parts.fragment if parts.fragment else ''
            return 'href="https://github.com/nvidia-omniverse/omniverse-labs/blob/main/' + resolved + anchor + '"'
        body = re.sub(r'href="([^"]+)"', source_link, body)
        article = ('    <article class="article-wrap blender-guide">\n'
                   '      <!-- Generated by scripts/sync-blender-guides.py; edit project Markdown. -->\n'
                   '      <p><a href="./">← Blender workflow overview</a></p>\n'
                   '      <div class="prose">\n' + body + '\n      </div>\n    </article>')
        page = shell[:start] + article + shell[end:]
        page = page.replace('https://nvidia-omniverse.github.io/omniverse-labs/projects/ov-blender-example/" />', 'https://nvidia-omniverse.github.io/omniverse-labs/projects/ov-blender-example/' + slug + '.html" />')
        page = re.sub(r'<title>.*?</title>', '<title>' + html.escape(title) + ' — Omniverse Labs</title>', page)
        (DEST / (slug + '.html')).write_text(page)
        print('Rendered', source.relative_to(ROOT), '->', slug + '.html')


if __name__ == '__main__':
    main()
