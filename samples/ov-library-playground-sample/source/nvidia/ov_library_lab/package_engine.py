"""Public ovpackage API; all mutations are confined to a fresh visitor workspace."""
import base64
from pathlib import Path
import tempfile
import ovpackage


class AssetHandoff:
    NAME = 'lab_delivery_robot'

    def __init__(self, runtime_root):
        parent = Path(runtime_root)/'package-workshops'
        parent.mkdir(parents=True, exist_ok=True)
        self.root = Path(tempfile.mkdtemp(prefix='visit-', dir=parent))
        self.repo, self.destination = self.root/'repository', self.root/'installed'
        self.catalogs = {}
        self.installed = None

    async def execute(self, request, scheduler):
        action = request['action']
        if action == 'publish':
            version = f'1.0.{len(self.catalogs)}'
            source = self.root/'sources'/version
            source.mkdir(parents=True)
            for name, encoded in request['files'].items():
                path = (source/name).resolve()
                if not path.is_relative_to(source.resolve()) or path == source.resolve():
                    raise ValueError('Package file path is outside the source directory')
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(base64.b64decode(encoded, validate=True))
            await ovpackage.create(self.NAME, version, str(source), catalog=False,
                                   repo=str(self.repo), scheduler=scheduler)
            self.catalogs[version] = await ovpackage.catalog(str(source), local_hash=True, scheduler=scheduler)
            return {'action': action, 'version': version, 'versions': list(self.catalogs),
                    'file_count': len(self.catalogs[version].items), 'workspace': str(self.root)}
        if action in ('install', 'restore'):
            version = request['version']
            if version not in self.catalogs:
                raise ValueError('Publish this revision before installing it')
            await ovpackage.install(self.NAME, version, str(self.destination),
                                    repo=str(self.repo), force=action == 'restore', scheduler=scheduler)
            self.installed = version
        elif action == 'edit':
            if not self.installed:
                raise ValueError('Install a revision first')
            # A deliberate, visible working-copy edit; not an ovpackage capability.
            path = self.destination/'robot.usda'
            text = path.read_text(encoding='utf-8')
            before = 'token visibility = "inherited"'
            if before not in text:
                raise ValueError('The installed asset has no visible cargo to edit')
            path.write_text(text.replace(before, 'token visibility = "invisible"', 1), encoding='utf-8')
        elif action != 'verify':
            raise ValueError('Unknown package operation')
        if not self.installed:
            raise ValueError('Install a revision first')
        actual = await ovpackage.catalog(str(self.destination), local_hash=True, scheduler=scheduler)
        # The install receipt is generated by ovpackage, not part of the asset.
        # Exclude that one receipt, retaining every unexpected user payload file.
        actual = actual.model_copy(update={'items': [item for item in actual.items
                                   if item.relative_path != '.'+self.NAME+'.wrapp']})
        missing, extra, changed = await ovpackage.diff_catalogs(self.catalogs[self.installed], actual, ignore_tags=True)
        return {'action': action, 'version': self.installed, 'versions': list(self.catalogs),
                'verified': not (missing or extra or changed), 'file_count': len(actual.items),
                'changed': [a['relative_path'] for a, b in changed],
                'missing': [a['relative_path'] for a in missing], 'extra': [a['relative_path'] for a in extra],
                'asset': str(self.destination/'robot.usda'), 'workspace': str(self.root),
                'hashes': {item.relative_path: item.hash for item in actual.items}}
